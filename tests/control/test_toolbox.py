@requires_podman
@pytest.mark.rule("toolbox.gives-every-need-in-use", "toolbox.each-system-package-is-checked")
def test_a_new_toolbox_is_checked_and_recorded(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """B.7 through the sandbox, as agents get it: each system package's check.sh (one failing
    fails the build), then where `command -v` finds each known command (the record)."""
    image = dev_env.CURL_IMAGE
    dev_env.ensure_image(image)
    settings = check_settings(tmp_path)
    mine = tmp_path / "system-packages"
    monkeypatch.setenv("HANDLER_SYSTEM_PACKAGES_DIR", str(mine))
    for name, check in (("ok", "command -v curl\n"), ("broken", "echo looking\ntest -x /nope\n")):
        (mine / name).mkdir(parents=True)
        (mine / name / "package.toml").write_text(
            f'apiVersion = "handler.system-package/v1"\nname = "{name}"\nversion = 1\n'
            f'description = "{name}"\nprovides = ["{name}"]\n'
        )
        (mine / name / "install-fedora.sh").write_text("true\n")
        (mine / name / "check.sh").write_text(check)
    lines: list[str] = []
    try:
        ok, broken = toolbox_parts.get("ok"), toolbox_parts.get("broken")
        asyncio.run(image_check.check_system_packages(settings, image, [ok], lines.append))
        with pytest.raises(image_check.ImageCheckError, match="broken: its check exited with 1"):
            asyncio.run(image_check.check_system_packages(settings, image, [broken], lines.append))
        commands = asyncio.run(
            image_check.toolbox_commands(settings, image, ["sh", "curl", "nope"], lines.append)
        )
    finally:
        dev_env.remove_scope(settings.state_dir)
    assert "check: system package ok ok" in lines and "broken: looking" in lines
    assert set(commands) == {"sh", "curl"} and commands["curl"].endswith("/curl")
