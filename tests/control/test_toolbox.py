@pytest.mark.rule("toolbox.made-of-its-three-parts")
def test_the_toolbox_is_made_of_the_users_choices(daemon: Daemon) -> None:
    """B.7: the default toolbox.toml seeded on first start; what it is made of, who needs what."""
    folder = daemon.config_dir / "toolbox"
    with daemon.http() as c:
        info = c.get("/v1/toolbox").json()
        generated = c.get("/v1/toolbox/containerfile").json()["content"]
    assert info["directory"] == str(folder) and info["distro"] == "fedora"
    assert [p["name"] for p in info["systemPackages"]] == ["podman", "wl-clipboard"]
    assert sorted(p.name for p in folder.iterdir()) == ["toolbox.toml"]
    needs = {tuple(n["commands"]): n for n in info["needs"]}
    assert needs[("sh",)] == {"commands": ["sh"], "neededBy": ["handler"], "providedBy": "base"}
    assert "harness:vibe" in needs[("uv",)]["neededBy"]
    assert generated.startswith("# Generated by Handler")
    assert "# system package podman 1\n" in generated and "# your lines" not in generated


@pytest.mark.rule("toolbox.made-of-its-three-parts")
def test_the_users_lines_and_system_packages_are_saved(daemon: Daemon) -> None:
    folder = daemon.config_dir / "toolbox"
    before = (folder / "toolbox.toml").read_text()
    try:
        with daemon.http() as c:
            assert c.get("/v1/toolbox/lines").json() == {"content": ""}
            mine = {"content": "RUN dnf -y install htop\n"}
            assert c.put("/v1/toolbox/lines", json=mine).json() == mine
            assert (
                c.put("/v1/toolbox/lines", json={"content": "x" * (256 * 1024 + 1)}).status_code
                == 422
            )
            assert (
                "# your lines (custom.containerfile)\nRUN dnf -y install htop\n"
                in (c.get("/v1/toolbox/containerfile").json()["content"])
            )
            body = {"systemPackages": ["podman", "wl-clipboard", "gcc"]}
            info = c.put("/v1/toolbox/system-packages", json=body).json()
            assert [p["name"] for p in info["systemPackages"]] == ["podman", "wl-clipboard", "gcc"]
            r = c.put("/v1/toolbox/system-packages", json={"systemPackages": ["nope"]})
            assert r.status_code == 400 and r.json()["title"] == "system packages refused"
            r = c.put("/v1/toolbox/system-packages", json={"systemPackages": ["Bad Name"]})
            assert r.status_code == 422
            offered = {p["name"]: p for p in c.get("/v1/toolbox/system-packages").json()}
            assert sorted(offered) == ["chromium", "docker", "gcc", "podman", "wl-clipboard"]
            assert offered["podman"]["builtin"] and offered["podman"]["distros"] == ["fedora"]
            assert offered["podman"]["caches"][0]["target"] == "~/.local/share/containers/storage"
            assert c.post("/v1/toolbox/rebuild", json={"update": "soon"}).status_code == 422
        assert (folder / "custom.containerfile").read_text() == mine["content"]
    finally:
        (folder / "toolbox.toml").write_text(before)
        (folder / "custom.containerfile").unlink(missing_ok=True)


def wait_ended(c: httpx.Client, build_id: str) -> dict:
    deadline = time.monotonic() + 30
    while (build := c.get(f"/v1/builds/{build_id}").json())["state"] == "running":
        assert time.monotonic() < deadline, build
        time.sleep(0.1)
    return build


@pytest.mark.rule("save.toolbox-additions-are-confirmed")
def test_a_save_adds_what_its_agent_needs_once_confirmed(daemon: Daemon) -> None:
    """B.6: an agent asking for `nested` on a toolbox without an engine is refused (409, the
    system packages to confirm in `toolboxAdds`); confirmed, it is saved, podman turned on and
    the toolbox applied (the tests' fake never builds it: that build fails)."""
    folder = daemon.config_dir / "toolbox"
    before = (folder / "toolbox.toml").read_text()
    body = {
        "model": {"account": "echo-box"},
        "scope": str(daemon.make_scope()),
        "confinement": "nested",
        "confirmRisks": True,
    }
    try:
        with daemon.http() as c:
            c.put("/v1/toolbox/system-packages", json={"systemPackages": ["wl-clipboard"]})
            r = c.post("/v1/agents", json=body)
            assert r.status_code == 409 and r.json()["title"] == "toolbox changes not confirmed"
            assert (
                r.json()["toolboxAdds"] == ["podman"]
                and "podman (for podman)" in r.json()["detail"]
            )
            agent = c.post("/v1/agents", json=body | {"toolboxAdds": ["podman"]})
            assert agent.status_code == 201, agent.text
            info = c.get("/v1/toolbox").json()
            assert [p["name"] for p in info["systemPackages"]] == ["wl-clipboard", "podman"]
            [build] = [b for b in c.get("/v1/builds").json() if b["target"] == "toolbox"][:1]
            assert wait_ended(c, build["id"])["state"] == "failed"
            again = c.put(f"/v1/agents/{agent.json()['id']}", json=body)  # on now: nothing to add
            assert again.status_code == 200, again.text
            assert c.delete(f"/v1/agents/{agent.json()['id']}").status_code == 204
    finally:
        (folder / "toolbox.toml").write_text(before)


@pytest.mark.rule("tool.built-once-it-can-be", "tool.installed-as-previewed")
def test_an_addon_brings_what_it_needs_to_the_toolbox(daemon: Daemon) -> None:
    """G.5, B.7: the preview says the system package of its source it adds; the install,
    confirmed, turns it on and applies the toolbox; the addon waits for it (preparing, then
    installed with what it lacks once that build failed)."""
    folder = daemon.config_dir / "toolbox"
    before = (folder / "toolbox.toml").read_text()
    source = "source:official/fake-toolchain"
    try:
        with daemon.http() as c:
            c.get("/v1/sources")  # read once
            seen = c.post("/v1/addons/preview", json={"source": source}).json()
            assert [a["name"] for a in seen["toolbox"]["adds"]] == ["fake-cc"]
            assert seen["toolbox"]["adds"][0]["source"] == "source:official/fake-cc"
            body = {"source": source, "digest": seen["digest"]}
            r = c.post("/v1/addons/install", json=body)
            assert r.status_code == 409 and r.json()["toolboxAdds"] == ["fake-cc"]
            installed = c.post("/v1/addons/install", json=body | {"toolboxAdds": ["fake-cc"]})
            assert installed.status_code == 201, installed.text
            build = installed.json()["build"]
            assert (
                build["target"] == "toolbox" and installed.json()["addon"]["state"] == "preparing"
            )
            assert wait_ended(c, build["id"])["state"] == "failed"
            addon = {a["name"]: a for a in c.get("/v1/addons").json()}["fake-toolchain"]
            assert addon["state"] == "installed"
            assert addon["stateDetail"] == "needs fake-cc: apply the toolbox"
            assert "fake-cc" in [p["name"] for p in c.get("/v1/toolbox").json()["systemPackages"]]
            assert c.delete("/v1/addons/fake-toolchain").status_code == 204
    finally:
        (folder / "toolbox.toml").write_text(before)
        shutil.rmtree(daemon.config_dir / "system-packages", ignore_errors=True)
        (daemon.config_dir / "system-packages.lock.toml").unlink(missing_ok=True)


