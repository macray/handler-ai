// Generates the TypeScript types of the web apps from the JSON Schemas in schemas/, themselves
// generated from the Python contracts (handler_contracts, the single source of truth). One output per
// app, from the documents it consumes. Run after changing contracts: `bun run gen:types` (root).
//   web UI         schemas/handler.control.v1.*  → packages/web-ui/src/lib/contracts.gen.ts (D)
//   remote client  schemas/handler.remote.v1.*  → packages/remote-client/src/lib/remote.gen.ts (D.7)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemasDir = join(root, "schemas");
const targets = [
  { prefix: "handler.control.v1.", out: "packages/web-ui/src/lib/contracts.gen.ts" },
  { prefix: "handler.remote.v1.", out: "packages/remote-client/src/lib/remote.gen.ts" },
];

/** Keep titles only on models (root and $defs): pydantic also titles every property, which would
 *  turn each field into its own named alias and make unrelated names collide (e.g. `Connection`).
 *  Walks schema keywords only: inside `properties`, keys are field names (a field may be named
 *  "title"), never annotations. */
type Schema = Record<string, unknown>;
const isSchema = (v: unknown): v is Schema => typeof v === "object" && v !== null && !Array.isArray(v);

function stripPropertyTitles(schema: Schema, isModel: boolean): void {
  if (!isModel) delete schema.title;
  for (const key of ["properties", "$defs"] as const) {
    const map = schema[key];
    if (isSchema(map)) for (const sub of Object.values(map)) if (isSchema(sub)) stripPropertyTitles(sub, key === "$defs");
  }
  for (const key of ["anyOf", "oneOf", "allOf", "prefixItems"] as const) {
    const list = schema[key];
    if (Array.isArray(list)) for (const sub of list) if (isSchema(sub)) stripPropertyTitles(sub, false);
  }
  for (const key of ["items", "additionalProperties", "not"] as const) {
    const sub = schema[key];
    if (isSchema(sub)) stripPropertyTitles(sub, false);
  }
}

async function generate(prefix: string, out: string): Promise<void> {
  const files = readdirSync(schemasDir)
    .filter((f) => f.startsWith(prefix) && f.endsWith(".schema.json"))
    .sort();
  const declared = new Set<string>();
  const chunks: string[] = [];
  for (const file of files) {
    const schema = JSON.parse(readFileSync(join(schemasDir, file), "utf8")) as JSONSchema;
    delete schema.$id; // keep names from titles, not URNs
    stripPropertyTitles(schema as Schema, true);
    const ts = await compile(schema, String(schema.title), {
      bannerComment: "",
      additionalProperties: false,
      format: false,
    });
    // Declarations shared by several schemas are emitted once.
    for (const block of ts.split(/\n(?=export )/)) {
      const name = /^export (?:interface|type) (\w+)/.exec(block.trim())?.[1];
      if (!name || declared.has(name)) continue;
      declared.add(name);
      chunks.push(block.trim());
    }
  }
  writeFileSync(
    join(root, out),
    [
      `// GENERATED by scripts/gen-types.ts from schemas/${prefix}* — do not edit.`,
      "/* eslint-disable */",
      "",
      ...chunks.map((c) => `${c}\n`),
    ].join("\n"),
  );
  console.log(`wrote ${declared.size} declarations to ${out}`);
}

for (const { prefix, out } of targets) await generate(prefix, out);
